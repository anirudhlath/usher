"""Price both suggest tiers at catalog scale, against a bar written first.

**Not a test, and not a fixture.** It reads a real database and takes the
catalog as it finds it -- it creates no title, enriches nothing, and the only
thing it writes is the two tier-1 prefix indexes it drops and rebuilds to time
them. Point it at a throwaway catalog, never at one somebody else is using.

    docker run -d --name usher-b3-pg -e POSTGRES_USER=usher \\
      -e POSTGRES_PASSWORD=usher -e POSTGRES_DB=usher -p 55434:5432 \\
      --shm-size=1g pgvector/pgvector:pg17
    export USHER_DATABASE_URL="postgresql+asyncpg://usher:usher@localhost:55434/usher"
    export USHER_SECRET_KEY="$(openssl rand -hex 32)"
    uv run alembic upgrade head
    uv run python scripts/measure_suggest_tiers.py --all

================================================================================
THE BAR -- written down, and committed, before any number was produced
================================================================================

M6's typo-tolerance gate failed its own bar on 2026-08-03 and that failure is
why tier 1 exists: the shipped trigram type-ahead finds the right title
**27.8%** of the time for a 2-4-character name and **68.3%** for 5-7, against
bars of 0.75 and 0.85; transposition on a short name is **0.0%**; and no
configuration under any threshold, cap or index type comes within **6x** of a
50 ms as-you-type budget. Above 8 characters it is 95-100% and needs nothing,
which is 91% of that catalog by row count.

This task decides whether tier 1 fixes it, so the bar goes first:

1. tier-1 p95 <= 10 ms at 1.27M titles;
2. tier-1 p95 over the union with `title_search_names` <= that same 10 ms;
3. tier-2's p50 after `m09a` is within +/-10% of the recorded **33.6 ms**, and
   its miss-diagnosis split (**63.6% below the `%` floor / 36.4% out-ranked /
   0.0% truncated by the cap / 0.0% dropped by the re-rank**) is unchanged;
4. tier-1 recall@5 on the gate's own 2,993 typo cases stays at the recorded
   **1.9%** -- a tier 1 that scores higher is not the index that was measured.

**"Tier-1 p95" is not one number, so it is three workloads and they are never
averaged together.** The gate's btree row -- p50 0.6 ms, p95 1.0 ms, max 10 ms
-- was measured over the 2,993 *typo strings*, which are whole mutated names:
long and highly selective. A keystroke is not that.

* **W1, gate-comparable.** The 2,993 typo strings as prefixes. The only
  workload whose numbers may be quoted against the gate's row, and the one
  bars (1), (2) and (4) are scored on.
* **W2, keystroke.** Prefixes of length 1..8 cut from real catalog names,
  equal draws per length, reported per length. Nothing in the gate is
  comparable to it.
* **W3, adversarial.** The single characters and two-character prefixes with
  the largest match sets. This is B2's named residual exposure -- *"a
  one-character prefix over a 1.27M-title catalog joined to
  `title_search_names`"* -- and B2 pointed it here by name.

A W1 pass with a W3 failure is a pass on bar (1) **and a reported defect**, in
that order and in those words. Tuning until a bar goes green is out of scope by
construction: if bar (2) fails, the recorded consequence is the one the plan
already names -- tier 1 scans `titles` only and `title_search_names` is
reachable from tier 2 alone.

Tolerances, fixed before the run: bar (3)'s +/-10% is 30.24 ms <= p50 <=
36.96 ms; "the split is unchanged" is each share within +/-5 points, with
**both zeros required to stay 0.0% exactly**, since a zero that moves at all is
a different finding. Bar (4)'s "stays at 1.9%" is 1.6%-2.2%.

**Bar (3)'s two halves name two different configurations and the plan pairs
them wrongly** -- found while building this harness, settled here, and settled
*before* the run rather than after seeing a number. ADR-0002's miss-diagnosis
table has a `GIN % @0.3 cap 200` row at **63.6/0/0/36.4** with p50 33.3 ms, and
a `GIN % @0.3 cap 200 + vote tiebreak` row -- the one that ships -- at
**82.8/0/0/17.2** with p50 **33.6 ms**. The bar quotes the tiebreak row's
latency and the other row's split, and `_SUGGEST` ships the tiebreak, so no
single run can satisfy both as written. The split is therefore **scored against
82.8/17.2 and reported against both**, with the plan's literal 63.6/36.4
printed beside it every time. `.claude/rules/search-and-embeddings.md` carries
the same mispairing in prose -- *"at the shipped configuration 63.6% fell below
the `%` floor"* -- and is corrected in the same commit as the number.

================================================================================
THE TYPO SET, AND WHY IT IS THE GATE'S OWN
================================================================================

Regenerated by the recorded procedure rather than restored from a file, because
**the test set is built from real catalog rows and is therefore not committed;
the measurement is.** Movies only, `vote_count >= 500`, names not unique in the
catalog excluded at sampling time, five equal draws of 150 over
`char_length(name)` bands 2-4 / 5-7 / 8-11 / 12-19 / 20+, four typo classes per
name at a uniformly random position, `random.Random(20260803)`, and 2,993 cases
rather than 3,000 because seven two-character names admit no deletion.

**The frame is verified rather than assumed**, and this is what makes the two
runs comparable at all: on the gate's catalog this procedure reproduces
**81,054** shared lower-cased names and eligible pools of **432 / 2,532 /
7,178 / 20,520 / 17,887** -- the five numbers the rules file records, to the
row. `--check-frame` prints them and refuses to go on if any differs.

What is *not* claimed: that the 750 sampled names are the same 750. The gate's
draw order was not recorded, only its procedure and its pool sizes, so a
different-but-equivalent draw is possible and every number here carries that
caveat.

================================================================================
WHAT ELSE IS RECORDED WITH EVERY NUMBER
================================================================================

The catalog's row count **and its bootstrap phase**, because
*"`popularity` IS NULL on all 1,271,138 rows"* was a `--phase imdb` fact read
as a catalog fact and it was wrong by half. The `title_search_names` row count
and its `kind` breakdown, beside every tier-1 figure, because a union over an
empty arm is not the union that ships -- and the script **refuses** to print a
union figure against an empty table.

And **whether the box was quiet, by a metric a clean run can actually pass.**
Every product of this script is a rate or a latency, so a number taken on a
loaded box is void -- but the first spelling of that guard compared the
one-minute load average before against after, which a forty-minute run of
continuous querying raises *by itself*. That guard condemns every clean run and
is a measurement of the work rather than of the box. What is read instead, at
two moments when this harness is deliberately idle, is the **foreign `pytest`
census** (this run spawns none, so any is somebody else's suite) and the
**drift** in non-idle CPU. A drift rather than a level, because this host's
always-on services idle at a baseline nobody has measured and an absolute
threshold guessed against it repeats the same mistake one level down. The load
average stays in the record as context and decides nothing.
"""

