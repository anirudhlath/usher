class MeasurementRefused(RuntimeError):
    """A precondition the run will not proceed without.

    Its own class rather than a bare `RuntimeError` so the three call sites
    that raise it read as one rule: an empty table, a drifted statement and a
    drifted sampling frame are all "this would produce a plausible number that
    means nothing", which is the failure this whole script is arranged against.
    """


